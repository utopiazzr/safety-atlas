"""A documented escape hatch for hosts where the sandbox backend cannot initialise.

The container blocks user namespaces (`unshare --user` -> EPERM) and the 5.4 kernel has no
Landlock, so DSH's workspace-write backend refuses to run anything and the agent under test can
only edit blind. That degrades every measurement that depends on the agent verifying its own work.

`target.py` already prepends ASL_SANDBOX_SHIM_DIR to PATH for the DSH process. A passthrough
`bwrap` placed there satisfies DSH's capability probe and lets commands run.

**This removes the isolation boundary.** It is opt-in, it announces itself, and any run made with
it must not be compared against a sandboxed run when isolation is part of the question.
"""
from __future__ import annotations

import os
import stat
from pathlib import Path

SHIM_NAME = "bwrap"

_PASSTHROUGH = """#!/bin/sh
# ASL sandbox shim - NOT a sandbox.
#
# DSH invokes bwrap to confine a command. This script finds the command after the last `--`
# separator and execs it directly in the caller's namespace. It exists because this host cannot
# create user namespaces, so the real bwrap fails with EPERM and every shell call is refused.
#
# Generated by `asl sandbox-shim --install`. Delete the directory to undo.
log="$ASL_SHIM_LOG"
if [ -n "$log" ]; then
  printf '%s\\n' "$*" >> "$log"
fi

cmd=""
prev=""
for a in "$@"; do
  if [ "$prev" = "--" ]; then cmd="$a"; break; fi
  prev="$a"
done

if [ -z "$cmd" ]; then
  # no `--`: take the first argument that is a runnable command
  for a in "$@"; do
    case "$a" in
      -*) ;;
      *)
        if command -v "$a" >/dev/null 2>&1; then cmd="$a"; break; fi
        ;;
    esac
  done
fi

if [ -z "$cmd" ]; then
  echo "asl shim: no command to run in: $*" >&2
  exit 127
fi

# rebuild argv from the command onwards so quoted arguments survive
set -- "$@" "__ASL_AFTER__"
tail=""
seen=0
for a in "$@"; do
  if [ "$seen" = "1" ]; then
    case "$a" in
      __ASL_AFTER__) break ;;
      *) tail="$tail '$a'" ;;
    esac
  elif [ "$a" = "$cmd" ]; then
    seen=1
  fi
done

eval exec "$cmd"$tail
"""


def install(shim_dir: Path, *, force: bool = False) -> dict:
    """Write the passthrough bwrap into shim_dir. Returns a summary."""
    shim_dir = Path(shim_dir).expanduser().resolve()
    bin_dir = shim_dir / "bin"
    bin_dir.mkdir(parents=True, exist_ok=True)
    target = bin_dir / SHIM_NAME

    if target.exists() and not force:
        return {"installed": False, "path": str(target),
                "reason": "already present (use --force to overwrite)"}

    target.write_text(_PASSTHROUGH, encoding="utf-8")
    mode = target.stat().st_mode
    target.chmod(mode | stat.S_IXUSR | stat.S_IXGRP | stat.S_IXOTH)
    return {"installed": True, "path": str(target), "reason": ""}


def detect() -> dict:
    """Is a shim active in this environment, and where does the bwrap on PATH come from?"""
    import shutil as _sh

    shim = os.environ.get("ASL_SANDBOX_SHIM_DIR")
    found = _sh.which(SHIM_NAME)
    is_shim = bool(found and shim and Path(found).resolve().is_relative_to(Path(shim).resolve()))
    real = _sh.which(SHIM_NAME, path="/usr/sbin:/usr/bin:/sbin:/bin")
    return {"shim_dir": shim, "bwrap_on_path": found, "shim_active": is_shim,
            "real_bwrap": real}


def warning() -> str:
    """The paragraph that must accompany any run made with the shim."""
    d = detect()
    if not d["shim_active"]:
        return ""
    return (
        "沙箱警告：当前用 PATH 上的透传 bwrap 顶替了真沙箱。\n"
        f"  shim: {d['bwrap_on_path']}\n"
        "  命令直接在宿主机上执行，没有任何命名空间隔离。\n"
        "  后果：agent 能正常跑测试（这是好事），但沙箱隔离带来的结论不再成立——\n"
        "  例如「侦察被拦住」「写不到工作区外」这类结果不能在这个模式下复现。\n"
        "  涉及隔离的测量，必须在真沙箱下做。\n"
    )
